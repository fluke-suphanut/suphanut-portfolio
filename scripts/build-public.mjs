// Public build (PM decision 2026-11-26): only the chosen design D, served at `/`.
//   - /a, /b, /c and the prototype chooser are not built at all, so they answer 404.
//   - /d redirects to / (301, Workers static assets `_redirects`).
//   - PORTFOLIO_PUBLIC=1: drops 'new_pending' rows, allows indexing, hides the links back to the chooser.
// It builds from a copy of the sources in .public-build/ with the prototype routes removed, so the local
// build (out/, served by `npm run preview` on :8787) and the source tree are never touched.
// Output: out-public/. Usage: DATABASE_URL=... node scripts/build-public.mjs
import { cp, mkdir, readFile, rename, rm, symlink, writeFile } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import path from "node:path";

const repo = process.cwd();
const stage = path.join(repo, ".public-build");
const out = path.join(repo, "out-public");
if (!process.env.DATABASE_URL) throw new Error("DATABASE_URL is not set");

await rm(stage, { recursive: true, force: true });
await mkdir(stage);
for (const f of ["app", "components", "lib", "public", "next.config.ts", "tsconfig.json", "package.json"])
  await cp(path.join(repo, f), path.join(stage, f), { recursive: true });
await symlink(path.join(repo, "node_modules"), path.join(stage, "node_modules"));

// Routes: drop the prototypes and the chooser; D moves to a private folder (not a route) and becomes `/`.
for (const f of ["app/a", "app/b", "app/c", "app/page.tsx", "app/fonts-c.ts", "public/demo"])
  await rm(path.join(stage, f), { recursive: true, force: true });
await rename(path.join(stage, "app/d"), path.join(stage, "app/_d"));
await writeFile(
  path.join(stage, "app/page.tsx"),
  `// Public home = prototype D (generated by scripts/build-public.mjs).\nexport { default, generateMetadata } from "./_d/page";\n`,
);
await writeFile(path.join(stage, "public/_redirects"), "/d / 301\n/d/ / 301\n");

// node_modules is a link into the repo, so Turbopack's root must be the repo.
const config = await readFile(path.join(stage, "next.config.ts"), "utf8");
const marker = "const nextConfig: NextConfig = {";
if (!config.includes(marker)) throw new Error("next.config.ts changed shape; update build-public.mjs");
await writeFile(
  path.join(stage, "next.config.ts"),
  config.replace(marker, `${marker}\n  turbopack: { root: ${JSON.stringify(repo)} },`),
);

const r = spawnSync(path.join(repo, "node_modules/.bin/next"), ["build"], {
  cwd: stage,
  stdio: "inherit",
  env: { ...process.env, PORTFOLIO_PUBLIC: "1", NEXT_TELEMETRY_DISABLED: "1" },
});
if (r.status !== 0) process.exit(r.status ?? 1);

await rm(out, { recursive: true, force: true });
await rename(path.join(stage, "out"), out);
await rm(stage, { recursive: true, force: true });
console.log(`public build written to ${path.relative(repo, out)}/`);
