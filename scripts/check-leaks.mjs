// AC3: scan the production build for things that must never ship.
// Usage: node scripts/check-leaks.mjs <n8n-inventory.md> [dir=out] [--images <assets/generated/README.md>]
//   --images (AC D6): every image file in the build must be a storybook-public demo drawing (out/demo/),
//   a file named in the generated-images README (out/d/), or a site icon file listed in its "Site icon (D6b)"
//   section and byte-identical to the copy in its icon/ folder.
//   --rules <file>: the private word list (default scripts/leak-rules.local.json, git-ignored). It holds the
//   owner's real names (domains, internal repo names, provenance file names) so they never enter the repo.
//   Start from scripts/leak-rules.example.json. The scan refuses to run without a rules file.
// Prints counts only (never the matched secrets themselves) and exits 1 on any hit.
import { readFile, readdir } from "node:fs/promises";
import path from "node:path";

const args = process.argv.slice(2);
const takeOpt = (flag) => {
  const at = args.indexOf(flag);
  return at >= 0 ? args.splice(at, 2)[1] : undefined;
};
const imagesReadme = takeOpt("--images");
const rulesFile = takeOpt("--rules") ?? path.join(import.meta.dirname, "leak-rules.local.json");
const [inventory, dir = "out"] = args;
if (!inventory) {
  console.error("usage: node scripts/check-leaks.mjs <n8n-inventory.md> [dir=out] [--rules <file>] [--images <README.md>]");
  process.exit(2);
}

// Private rules: { "rules": [{ "name", "pattern", "flags"?, "only"? }] }. `only` limits a rule to matching file names.
const rulesText = await readFile(rulesFile, "utf8").catch(() => null);
if (rulesText === null) {
  console.error(`no rules file at ${rulesFile}: copy scripts/leak-rules.example.json to scripts/leak-rules.local.json and fill it in`);
  process.exit(2);
}
const privateRules = JSON.parse(rulesText).rules.map((r) => ({
  name: r.name,
  re: new RegExp(r.pattern, r.flags ?? "g"),
  ...(r.only ? { only: new RegExp(r.only) } : {}),
}));
if (privateRules.length === 0) {
  console.error(`${rulesFile} has no rules: refusing to report a clean scan`);
  process.exit(2);
}

// n8n workflow IDs: first cell of each data row in the inventory table.
const ids = (await readFile(inventory, "utf8"))
  .split("\n")
  .filter((l) => l.startsWith("|") && !/^\|\s*(id|-+)\s*\|/i.test(l))
  // cells are written as `id` in Markdown: strip the backticks so the bare ID is what gets searched
  .map((l) => l.split("|")[1].replace(/`/g, "").trim())
  .filter((id) => /^[A-Za-z0-9_-]{6,}$/.test(id));
if (ids.length === 0) {
  console.error(`no workflow IDs parsed from ${inventory}: refusing to report a clean scan`);
  process.exit(2);
}

const TEXT = /\.(html|txt|js|css|json|svg|map|xml|webmanifest)$/;
const files = [];
async function walk(d) {
  for (const e of await readdir(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) await walk(p);
    else if (TEXT.test(e.name)) files.push(p);
  }
}
await walk(dir);

const checks = [
  { name: "macOS home path", re: /\/Users\//g },
  { name: "private IP 10.x", re: /\b10\.\d{1,3}\.\d{1,3}\.\d{1,3}\b/g },
  { name: "private IP 192.168.x", re: /\b192\.168\.\d{1,3}\.\d{1,3}\b/g },
  { name: "private IP 172.16-31.x", re: /\b172\.(1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3}\b/g },
  { name: "Thai mobile 06x/08x/09x", re: /(?<![\d.])0[689]\d[-\s]?\d{3}[-\s]?\d{4}(?![\d.])/g },
  { name: "evidence code E-nn (html/txt)", re: /\bE-\d{1,3}\b/g, only: /\.(html|txt)$/ },
  ...privateRules.map((r) => ({ ...r, name: `${r.name} (private rules)` })),
  { name: `n8n workflow IDs (${ids.length} from inventory)`, ids },
];

let total = 0;
for (const c of checks) {
  let hits = 0;
  const where = new Set();
  for (const f of files) {
    if (c.only && !c.only.test(f)) continue;
    const s = await readFile(f, "utf8");
    const n = c.ids ? c.ids.reduce((a, id) => a + s.split(id).length - 1, 0) : (s.match(c.re) ?? []).length;
    if (n) { hits += n; where.add(path.relative(dir, f)); }
  }
  total += hits;
  console.log(`${hits ? "FAIL" : "ok  "} ${String(hits).padStart(3)}  ${c.name}${hits ? `  in ${[...where].slice(0, 5).join(", ")}` : ""}`);
}
console.log(`${files.length} text files scanned in ${dir}/`);

if (imagesReadme) {
  const readme = await readFile(imagesReadme, "utf8");
  const IMAGE = /\.(png|jpe?g|webp|gif|avif|svg|ico)$/i;
  const images = [];
  async function walkAll(d) {
    for (const e of await readdir(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) await walkAll(p);
      else if (IMAGE.test(e.name)) images.push(path.relative(dir, p));
    }
  }
  await walkAll(dir);
  // Site icon (PRD addendum D6b, 2026-11-26): generated by Codex, listed in the README's "Site icon (D6b)" section,
  // and kept next to it in icon/. Next emits each file twice: at the root and as a hashed copy under
  // _next/static/media. Both must be byte-identical to the listed file. No other icon (and no svg) is allowed.
  const ICONS = ["favicon.ico", "icon.png", "apple-icon.png"];
  const iconAt = readme.indexOf("## Site icon (D6b)");
  const iconEnd = readme.indexOf("\n## ", iconAt + 3);
  const iconSection = iconAt < 0 ? "" : readme.slice(iconAt, iconEnd < 0 ? undefined : iconEnd);
  const iconBytes = new Map(
    await Promise.all(
      ICONS.filter((n) => iconSection.includes(`\`${n}\``)).map(async (n) => [
        n,
        await readFile(path.join(path.dirname(imagesReadme), "icon", n)).catch(() => null),
      ]),
    ),
  );
  const iconOf = (rel) => {
    const m = rel.match(/^(?:_next\/static\/media\/)?([a-z-]+)(?:\.[\w-]+)?\.(ico|png)$/);
    const n = m && `${m[1]}.${m[2]}`;
    const root = n && rel === n;
    const hashed = n && rel.startsWith("_next/static/media/");
    return n && (root || hashed) && ICONS.includes(n) ? n : null;
  };
  const bytes = new Map(await Promise.all(images.filter(iconOf).map(async (r) => [r, await readFile(path.join(dir, r))])));
  // README forms: full name, `stem-{720,1440}.webp`, or `stem-720.webp` (...), `-1440.webp` on one row
  const listed = (name) => {
    const stem = name.replace(/-\d+\.webp$/, "");
    const size = name.match(/-(\d+)\.webp$/)?.[1];
    return readme.includes(name) || readme.includes(`${stem}-{`) ||
      (!!size && readme.split("\n").some((l) => l.includes(`${stem}-`) && l.includes(`-${size}.webp`)));
  };
  const verdict = images.map((rel) => {
    const name = path.basename(rel);
    const icon = iconOf(rel);
    if (icon && iconBytes.get(icon)?.equals(bytes.get(rel))) return [rel, "site icon (listed in generated README, D6b)"];
    if (rel.startsWith("demo/") && /^[a-z0-9-]+-(screen|result|flow)-(720|1440)\.webp$/.test(name)) return [rel, "storybook-public demo"];
    if (rel.startsWith("d/") && listed(name)) return [rel, "listed in generated README"];
    return [rel, null];
  });
  const bad = verdict.filter(([, why]) => !why);
  const by = (w) => verdict.filter(([, why]) => why === w).length;
  console.log(`${bad.length ? "FAIL" : "ok  "} ${String(bad.length).padStart(3)}  images not accounted for (D6): ${images.length} images = ` +
    `${by("storybook-public demo")} demo + ${by("listed in generated README")} generated/profile + ${by("site icon (listed in generated README, D6b)")} icon`);
  for (const [rel] of bad) console.log(`       ${rel}`);
  total += bad.length;
}
process.exit(total ? 1 : 0);
